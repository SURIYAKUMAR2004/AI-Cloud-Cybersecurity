import time
from pathlib import Path

import pandas as pd

from security.aws_cloudtrail_collector import (
    collect_cloudtrail_events,
)

from security.security_orchestrator import (
    analyze_security_events,
)


# ==========================================================
# CONFIGURATION
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parents[1]

AWS_EVENTS_FILE = (
    PROJECT_ROOT
    / "data"
    / "aws_cloudtrail_events.csv"
)

INCIDENTS_FILE = (
    PROJECT_ROOT
    / "data"
    / "aws_realtime_incidents.csv"
)

POLL_INTERVAL_SECONDS = 60
CLOUDTRAIL_BATCH_SIZE = 20


# ==========================================================
# LOAD EXISTING AWS EVENTS
# ==========================================================

def load_existing_events():
    """
    Load previously stored AWS CloudTrail events.
    """

    if not AWS_EVENTS_FILE.exists():
        return pd.DataFrame()

    try:
        df = pd.read_csv(AWS_EVENTS_FILE)

        if df.empty:
            return pd.DataFrame()

        return df

    except Exception as error:
        print(
            f"⚠️ Could not load existing AWS events: {error}"
        )

        return pd.DataFrame()


# ==========================================================
# SAVE INCIDENT RESULTS
# ==========================================================

def save_incidents(incidents):
    """
    Save AI-generated correlated security incidents.
    """

    if incidents is None or incidents.empty:
        print(
            "ℹ️ No correlated security incidents "
            "generated by the orchestrator."
        )

        return

    try:

        INCIDENTS_FILE.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        incidents.to_csv(
            INCIDENTS_FILE,
            index=False
        )

        print(
            f"🚨 AI incidents generated: "
            f"{len(incidents)}"
        )

        print(
            f"💾 Incidents saved to: "
            f"{INCIDENTS_FILE}"
        )

    except Exception as error:

        print(
            f"❌ Could not save AI incidents: {error}"
        )


# ==========================================================
# RUN AI SECURITY PIPELINE
# ==========================================================

def analyze_aws_security_events(events_df):
    """
    Send accumulated AWS CloudTrail events through
    the complete AI security orchestrator.
    """

    if events_df is None or events_df.empty:

        print(
            "ℹ️ No AWS events available for AI analysis."
        )

        return pd.DataFrame()

    print("\n")
    print("=" * 60)
    print("🤖 AI SECURITY ORCHESTRATOR")
    print("=" * 60)

    print(
        f"📊 AWS events available for analysis: "
        f"{len(events_df)}"
    )

    try:

        incidents = analyze_security_events(
            events_df.copy()
        )

        if incidents is None or incidents.empty:

            print(
                "✅ AI analysis completed."
            )

            print(
                "🟢 No correlated security incidents detected."
            )

            return pd.DataFrame()

        print(
            "\n🚨 CORRELATED SECURITY INCIDENTS"
        )

        print(
            "-" * 60
        )

        display_columns = [
            "incident_id",
            "user",
            "source_ip",
            "severity",
            "assessment",
            "events_correlated",
            "final_risk_score",
            "final_risk_level",
            "response",
            "priority",
            "execution_mode",
        ]

        available_columns = [
            column
            for column in display_columns
            if column in incidents.columns
        ]

        print(
            incidents[
                available_columns
            ].to_string(index=False)
        )

        print(
            "-" * 60
        )

        save_incidents(incidents)

        return incidents

    except Exception as error:

        print(
            f"❌ AI security analysis failed: {error}"
        )

        return pd.DataFrame()


# ==========================================================
# COLLECT + STORE + ANALYZE
# ==========================================================

def collect_and_analyze():
    """
    Complete AWS real-time security cycle.

    1. Collect CloudTrail events
    2. Deduplicate events
    3. Store events
    4. Detect newly added events
    5. Run complete AI security orchestration
    """

    print("\n")
    print("=" * 60)
    print("☁️ AWS CLOUDTRAIL SECURITY MONITOR")
    print("=" * 60)

    # ------------------------------------------------------
    # 1. COLLECT AWS CLOUDTRAIL EVENTS
    # ------------------------------------------------------

    try:

        new_events = collect_cloudtrail_events(
            max_results=CLOUDTRAIL_BATCH_SIZE
        )

    except Exception as error:

        print(
            f"❌ AWS CloudTrail collection failed: {error}"
        )

        return

    if not new_events:

        print(
            "ℹ️ No CloudTrail events returned."
        )

        return

    new_df = pd.DataFrame(
        new_events
    )

    if new_df.empty:

        print(
            "ℹ️ No usable CloudTrail events found."
        )

        return

    # ------------------------------------------------------
    # 2. LOAD EXISTING EVENTS
    # ------------------------------------------------------

    existing_df = load_existing_events()

    # ------------------------------------------------------
    # 3. COMBINE EVENTS
    # ------------------------------------------------------

    if existing_df.empty:

        combined = new_df.copy()

    else:

        combined = pd.concat(
            [
                existing_df,
                new_df
            ],
            ignore_index=True
        )

    # ------------------------------------------------------
    # 4. DEDUPLICATION
    # ------------------------------------------------------

    if "event_id" in combined.columns:

        combined = combined.drop_duplicates(
            subset=["event_id"],
            keep="last"
        )

    # ------------------------------------------------------
    # 5. NORMALIZE TIMESTAMP
    # ------------------------------------------------------

    if "timestamp" in combined.columns:

        combined["timestamp"] = pd.to_datetime(
            combined["timestamp"],
            errors="coerce",
            utc=True
        )

        combined = combined.sort_values(
            "timestamp",
            na_position="last"
        )

    # ------------------------------------------------------
    # 6. SAVE AWS EVENTS
    # ------------------------------------------------------

    AWS_EVENTS_FILE.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    combined.to_csv(
        AWS_EVENTS_FILE,
        index=False
    )

    # ------------------------------------------------------
    # 7. CALCULATE NEW UNIQUE EVENTS
    # ------------------------------------------------------

    existing_ids = set()

    if (
        not existing_df.empty
        and "event_id" in existing_df.columns
    ):

        existing_ids = set(
            existing_df[
                "event_id"
            ]
            .dropna()
            .astype(str)
        )

    new_ids = set()

    if "event_id" in new_df.columns:

        new_ids = set(
            new_df[
                "event_id"
            ]
            .dropna()
            .astype(str)
        )

    added_ids = (
        new_ids - existing_ids
    )

    added_count = len(
        added_ids
    )

    # ------------------------------------------------------
    # 8. DISPLAY COLLECTION STATUS
    # ------------------------------------------------------

    print(
        f"📥 CloudTrail events received: "
        f"{len(new_df)}"
    )

    print(
        f"➕ New unique events added: "
        f"{added_count}"
    )

    print(
        f"📊 Total stored AWS events: "
        f"{len(combined)}"
    )

    print(
        f"💾 Saved to: "
        f"{AWS_EVENTS_FILE}"
    )

    # ------------------------------------------------------
    # 9. RUN COMPLETE AI SECURITY ORCHESTRATOR
    # ------------------------------------------------------

    incidents = analyze_aws_security_events(
        combined
    )

    # ------------------------------------------------------
    # 10. FINAL STATUS
    # ------------------------------------------------------

    print("\n")
    print("=" * 60)
    print("✅ REAL-TIME AWS SECURITY CYCLE COMPLETED")
    print("=" * 60)

    print(
        f"AWS events stored: {len(combined)}"
    )

    print(
        f"New events detected: {added_count}"
    )

    print(
        f"AI incidents detected: {len(incidents)}"
    )

    if not incidents.empty:

        high_risk_count = 0

        if "final_risk_level" in incidents.columns:

            high_risk_count = len(
                incidents[
                    incidents[
                        "final_risk_level"
                    ].isin(
                        [
                            "HIGH",
                            "CRITICAL"
                        ]
                    )
                ]
            )

        print(
            f"🔴 High/Critical incidents: "
            f"{high_risk_count}"
        )

    print("=" * 60)


# ==========================================================
# CONTINUOUS AWS MONITOR
# ==========================================================

def monitor():

    print("\n")

    print("=" * 60)

    print(
        "🔐 AI CLOUD CYBERSECURITY"
    )

    print(
        "☁️ AWS CLOUDTRAIL REAL-TIME AI MONITOR"
    )

    print("=" * 60)

    print(
        f"Polling interval: "
        f"{POLL_INTERVAL_SECONDS} seconds"
    )

    print(
        f"CloudTrail batch size: "
        f"{CLOUDTRAIL_BATCH_SIZE}"
    )

    print(
        "AI Security Orchestrator: ENABLED"
    )

    print(
        "Response execution: SIMULATION ONLY"
    )

    print(
        "Press Ctrl+C to stop."
    )

    print("=" * 60)

    while True:

        try:

            collect_and_analyze()

            print(
                f"\n⏳ Waiting "
                f"{POLL_INTERVAL_SECONDS} seconds..."
            )

            time.sleep(
                POLL_INTERVAL_SECONDS
            )

        except KeyboardInterrupt:

            print(
                "\n\n🛑 AWS monitoring stopped."
            )

            break

        except Exception as error:

            print(
                f"\n❌ Monitor error: {error}"
            )

            print(
                "Retrying..."
            )

            time.sleep(
                POLL_INTERVAL_SECONDS
            )


# ==========================================================
# MAIN
# ==========================================================

if __name__ == "__main__":

    monitor()
